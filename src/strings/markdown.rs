// HTML Compiler
// ============================================================================

/// Compiles a stream of Markdown events into an HTML string.
///
/// # RUST INSIGHT:
/// Taking an `Iterator<Item = Event<'a>>` allows the compiler to consume the parser lazily.
/// We use `String::with_capacity` to minimize intermediate heap allocations while building the HTML.
pub fn push_html<'a, I>(html: &mut String, iter: I)
where
    I: Iterator<Item = Event<'a>>,
{
    for event in iter {
        match event {
            Event::Start(tag) => match tag {
                Tag::Paragraph => html.push_str("<p>"),
                Tag::Heading(level) => {
                    html.push_str("<h");
                    html.push(std::char::from_digit(level, 10).unwrap());
                    html.push('>');
                }
                Tag::BlockQuote => html.push_str("<blockquote>\n"),
                Tag::CodeBlock(lang) => {
                    html.push_str("<pre><code");
                    if !lang.is_empty() {
                        html.push_str(" class=\"language-");
                        html.push_str(lang);
                        html.push('"');
                    }
                    html.push('>');
                }
                Tag::List(Some(start)) => {
                    html.push_str("<ol start=\"");
                    html.push_str(&start.to_string());
                    html.push_str("\">\n");
                }
                Tag::List(None) => html.push_str("<ul>\n"),
                Tag::Item => html.push_str("<li>"),
                Tag::Emphasis => html.push_str("<em>"),
                Tag::Strong => html.push_str("<strong>"),
                Tag::Link(url, title) => {
                    html.push_str("<a href=\"");
                    html.push_str(url);
                    html.push('"');
                    if !title.is_empty() {
                        html.push_str(" title=\"");
                        html.push_str(title);
                        html.push('"');
                    }
                    html.push('>');
                }
                Tag::Image(url, title) => {
                    html.push_str("<img src=\"");
                    html.push_str(url);
                    html.push('"');
                    if !title.is_empty() {
                        html.push_str(" title=\"");
                        html.push_str(title);
                        html.push('"');
                    }
                    html.push_str(" alt=\"");
                }
            },
            Event::End(tag) => match tag {
                Tag::Paragraph => html.push_str("</p>\n"),
                Tag::Heading(level) => {
                    html.push_str("</h");
                    html.push(std::char::from_digit(level, 10).unwrap());
                    html.push_str(">\n");
                }
                Tag::BlockQuote => html.push_str("</blockquote>\n"),
                Tag::CodeBlock(_) => html.push_str("</code></pre>\n"),
                Tag::List(Some(_)) => html.push_str("</ol>\n"),
                Tag::List(None) => html.push_str("</ul>\n"),
                Tag::Item => html.push_str("</li>\n"),
                Tag::Emphasis => html.push_str("</em>"),
                Tag::Strong => html.push_str("</strong>"),
                Tag::Link(_, _) => html.push_str("</a>"),
                Tag::Image(_, _) => html.push_str("\" />"),
            },
            Event::Text(text) => escape_html(html, text),
            Event::Code(text) => {
                html.push_str("<code>");
                escape_html(html, text);
                html.push_str("</code>");
            }
            Event::Html(html_block) => html.push_str(html_block),
            Event::SoftBreak => html.push('\n'),
            Event::HardBreak => html.push_str("<br />\n"),
        }
    }
}

/// Escapes HTML characters to prevent XSS.
fn escape_html(out: &mut String, text: &str) {
    for c in text.chars() {
        match c {
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '&' => out.push_str("&amp;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
}

