//! # Markdown Parser
//!
//! What this implements and what crate(s) it replaces:
//! This is a from-scratch implementation of a Markdown to HTML compiler.
//! It replaces crates like `pulldown-cmark` and `comrak`.
//!
//! Real-world systems that use this:
//! Markdown parsers are ubiquitous in static site generators (Hugo, Jekyll),
//! documentation tools (mdBook, Rustdoc), and forums (Discourse).
//!
//! Why build it yourself?
//! Parsing a loosely structured, human-readable format like Markdown requires a
//! balance between structured state machines (for blocks) and flexible scanning
//! (for inlines). Building it teaches pull-based event streaming, mitigating the
//! memory footprint of a full AST by generating output on-the-fly.
//!
//! ## Architecture
//!
//! ```text
//! Markdown Text
//!      │
//!      ▼
//! [ Block Parser ] --> Identifies block boundaries (Headings, Paragraphs, Lists)
//!      │
//!      ▼
//! [ Inline Parser ] --> Parses text within blocks (Strong, Emphasis, Links)
//!      │
//!      ▼
//! [ Event Stream ] --> Yields `Start(Heading)`, `Text("Hello")`, `End(Heading)`
//!      │
//!      ▼
//! [ HTML Compiler ] --> Converts events to `<h1>Hello</h1>`
//! ```
//!
//! ### Invariants
//! - Block parsing must correctly manage nesting (e.g., lists within blockquotes).
//! - Inline formatting tokens must match pairs appropriately and handle escaping.
//!
//! ### Time/Space Complexity
//! - **Parsing**: `O(N)` time where `N` is the size of the input document. The pull-based approach
//!   uses `O(D)` space where `D` is the depth of nesting (very small).
//! - **HTML Generation**: `O(N)` time and space to build the final HTML string.
//!
//! ### Design Decisions
//! - **Pull-based Parser**: We implement an iterator yielding `Event`s rather than building an AST.
//!   This is the same design as `pulldown-cmark` and prevents large memory overhead.

// ============================================================================
// Core Types
// ============================================================================

#[derive(Debug, PartialEq)]
pub enum Tag<'a> {
    Paragraph,
    Heading(u32),
    BlockQuote,
    CodeBlock(&'a str), // Language
    List(Option<u64>),  // None for unordered, Some(start) for ordered
    Item,
    Emphasis,
    Strong,
    Link(&'a str, &'a str), // URL, Title
    Image(&'a str, &'a str), // URL, Title
}

#[derive(Debug, PartialEq)]
pub enum Event<'a> {
    Start(Tag<'a>),
    End(Tag<'a>),
    Text(&'a str),
    Code(&'a str),
    Html(&'a str),
    SoftBreak,
    HardBreak,
}

// ============================================================================
// Parser
// ============================================================================

pub struct Parser<'a> {
    input: &'a str,
    pos: usize,
    /// Stack of currently open tags to ensure we close them properly
    stack: Vec<Tag<'a>>,
    /// Lookahead buffer for events generated by inline parsing
    events: Vec<Event<'a>>,
}

impl<'a> Parser<'a> {
    #[must_use]
    pub fn new(input: &'a str) -> Self {
        Self {
            input,
            pos: 0,
            stack: Vec::new(),
            events: Vec::new(),
        }
    }

    /// Advances the parser and returns the next event.
    fn next_event(&mut self) -> Option<Event<'a>> {
        if !self.events.is_empty() {
            return Some(self.events.remove(0));
        }

        if self.pos >= self.input.len() {
            return self.stack.pop().map(Event::End);
        }

        self.parse_block()
    }

    /// Parses the next block-level element.
    fn parse_block(&mut self) -> Option<Event<'a>> {
        self.skip_blank_lines();
        if self.pos >= self.input.len() {
            return None;
        }

        let slice = &self.input[self.pos..];

        // Heading
        if slice.starts_with('#') {
            let mut level = 0;
            let mut iter = slice.chars();
            while let Some('#') = iter.next() {
                level += 1;
            }
            if level > 0 && level <= 6 && iter.next() == Some(' ') {
                self.pos += level as usize + 1;
                return self.parse_heading(level);
            }
        }

        // Fenced Code Block
        if slice.starts_with("```") {
            return self.parse_fenced_code_block();
        }

        // Blockquote
        if slice.starts_with("> ") {
            return self.parse_blockquote();
        }

        // Unordered List Item
        if slice.starts_with("- ") || slice.starts_with("* ") {
            // Simplified: we treat each item as a standalone list for now if not already in one
            return self.parse_list_item();
        }

        // Paragraph (Fallback)
        self.parse_paragraph()
    }

    fn skip_blank_lines(&mut self) {
        while self.pos < self.input.len() {
            let slice = &self.input[self.pos..];
            if slice.starts_with("\n\n") {
                self.pos += 2;
            } else if slice.starts_with('\n') {
                self.pos += 1;
            } else if slice.starts_with("\r\n") {
                self.pos += 2;
            } else {
                break;
            }
        }
    }

    fn read_until_newline(&mut self) -> &'a str {
        let start = self.pos;
        while self.pos < self.input.len() {
            if self.input[self.pos..].starts_with('\n') {
                let text = &self.input[start..self.pos];
                self.pos += 1;
                return text;
            }
            // GOTCHA: Use `char.len_utf8()` to advance safely.
            let c = self.input[self.pos..].chars().next().unwrap();
            self.pos += c.len_utf8();
        }
        &self.input[start..]
    }

    fn parse_heading(&mut self, level: u32) -> Option<Event<'a>> {
        let text = self.read_until_newline();
        self.events.push(Event::Start(Tag::Heading(level)));
        self.parse_inline(text);
        self.events.push(Event::End(Tag::Heading(level)));
        self.next_event()
    }

    fn parse_fenced_code_block(&mut self) -> Option<Event<'a>> {
        self.pos += 3; // Skip ```
        let lang = self.read_until_newline().trim();
        let start = self.pos;

        while self.pos < self.input.len() {
            if self.input[self.pos..].starts_with("```") {
                let code = &self.input[start..self.pos];
                self.pos += 3; // Skip ```
                self.read_until_newline(); // Consume rest of line

                self.events.push(Event::Start(Tag::CodeBlock(lang)));
                self.events.push(Event::Text(code));
                self.events.push(Event::End(Tag::CodeBlock(lang)));
                return self.next_event();
            }
            let c = self.input[self.pos..].chars().next().unwrap();
            self.pos += c.len_utf8();
        }

        // Unclosed code block
        let code = &self.input[start..];
        self.events.push(Event::Start(Tag::CodeBlock(lang)));
        self.events.push(Event::Text(code));
        self.events.push(Event::End(Tag::CodeBlock(lang)));
        self.next_event()
    }

    fn parse_blockquote(&mut self) -> Option<Event<'a>> {
        self.events.push(Event::Start(Tag::BlockQuote));
        self.events.push(Event::Start(Tag::Paragraph));

        while self.pos < self.input.len() {
            if self.input[self.pos..].starts_with("> ") {
                self.pos += 2;
                let line = self.read_until_newline();
                self.parse_inline(line);
                self.events.push(Event::SoftBreak);
            } else if self.input[self.pos..].starts_with('\n') {
                self.pos += 1;
                break; // End of blockquote
            } else {
                break;
            }
        }

        self.events.push(Event::End(Tag::Paragraph));
        self.events.push(Event::End(Tag::BlockQuote));
        self.next_event()
    }

    fn parse_list_item(&mut self) -> Option<Event<'a>> {
        self.pos += 2; // Skip "- "
        let text = self.read_until_newline();
        self.events.push(Event::Start(Tag::List(None)));
        self.events.push(Event::Start(Tag::Item));
        self.parse_inline(text);
        self.events.push(Event::End(Tag::Item));
        self.events.push(Event::End(Tag::List(None)));
        self.next_event()
    }

    fn parse_paragraph(&mut self) -> Option<Event<'a>> {
        let mut end = self.pos;
        while end < self.input.len() {
            if self.input[end..].starts_with("\n\n") {
                break;
            }
            let c = self.input[end..].chars().next().unwrap();
            end += c.len_utf8();
        }

        let text = &self.input[self.pos..end];
        self.pos = end;

        self.events.push(Event::Start(Tag::Paragraph));
        self.parse_inline(text);
        self.events.push(Event::End(Tag::Paragraph));

        self.next_event()
    }

    // ============================================================================
    // Inline Parser
    // ============================================================================

    /// Extremely simplified inline parser.
    fn parse_inline(&mut self, text: &'a str) {
        let mut i = 0;
        let mut last = 0;

        while i < text.len() {
            let slice = &text[i..];

            // Strong (**text**)
            if slice.starts_with("**") {
                let mut search_idx = i + 2;
                let mut found = false;
                while search_idx < text.len() {
                    if text[search_idx..].starts_with("**") {
                        found = true;
                        break;
                    }
                    let c = text[search_idx..].chars().next().unwrap();
                    search_idx += c.len_utf8();
                }

                if found {
                    if i > last {
                        self.events.push(Event::Text(&text[last..i]));
                    }
                    self.events.push(Event::Start(Tag::Strong));
                    self.events.push(Event::Text(&text[i + 2..search_idx]));
                    self.events.push(Event::End(Tag::Strong));
                    i = search_idx + 2;
                    last = i;
                    continue;
                }
            }

            // Emphasis (*text*)
            if slice.starts_with('*') && !slice.starts_with("**") {
                let mut search_idx = i + 1;
                let mut found = false;
                while search_idx < text.len() {
                    if text[search_idx..].starts_with('*') && !text[search_idx..].starts_with("**") {
                        found = true;
                        break;
                    }
                    let c = text[search_idx..].chars().next().unwrap();
                    search_idx += c.len_utf8();
                }

                if found {
                    if i > last {
                        self.events.push(Event::Text(&text[last..i]));
                    }
                    self.events.push(Event::Start(Tag::Emphasis));
                    self.events.push(Event::Text(&text[i + 1..search_idx]));
                    self.events.push(Event::End(Tag::Emphasis));
                    i = search_idx + 1;
                    last = i;
                    continue;
                }
            }

            // Inline Code (`code`)
            if slice.starts_with('`') {
                let mut search_idx = i + 1;
                let mut found = false;
                while search_idx < text.len() {
                    if text[search_idx..].starts_with('`') {
                        found = true;
                        break;
                    }
                    let c = text[search_idx..].chars().next().unwrap();
                    search_idx += c.len_utf8();
                }

                if found {
                    if i > last {
                        self.events.push(Event::Text(&text[last..i]));
                    }
                    self.events.push(Event::Code(&text[i + 1..search_idx]));
                    i = search_idx + 1;
                    last = i;
                    continue;
                }
            }

            // Link ([text](url))
            if slice.starts_with('[') {
                if let Some(close_bracket) = text[i..].find(']') {
                    if text[i + close_bracket..].starts_with("](") {
                        if let Some(close_paren) = text[i + close_bracket..].find(')') {
                            if i > last {
                                self.events.push(Event::Text(&text[last..i]));
                            }
                            let link_text = &text[i + 1..i + close_bracket];
                            let url = &text[i + close_bracket + 2..i + close_bracket + close_paren];

                            self.events.push(Event::Start(Tag::Link(url, "")));
                            // Ideally recursively parse link_text, but we'll just emit Text
                            self.events.push(Event::Text(link_text));
                            self.events.push(Event::End(Tag::Link(url, "")));

                            i += close_bracket + close_paren + 1;
                            last = i;
                            continue;
                        }
                    }
                }
            }

            let c = text[i..].chars().next().unwrap();
            i += c.len_utf8();
        }

        if last < text.len() {
            self.events.push(Event::Text(&text[last..]));
        }
    }
}

impl<'a> Iterator for Parser<'a> {
    type Item = Event<'a>;

    fn next(&mut self) -> Option<Self::Item> {
        self.next_event()
    }
}

