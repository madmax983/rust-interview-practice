// Footer
// ============================================================================
//
// Comparison to Canonical Crates:
// - `pulldown-cmark`: A robust, fully spec-compliant (CommonMark) parser. It handles complex
//   nested blocks, link reference definitions, and uses advanced state machines.
// - `comrak`: An AST-based parser that supports GFM (GitHub Flavored Markdown) extensions.
//
// What's missing vs. production:
// - **CommonMark Compliance**: We only support a tiny subset. Real Markdown has hundreds of edge
//   cases regarding block termination, nested lists, and HTML blocks.
// - **References**: We don't support `[link][ref]` syntax which requires a two-pass architecture.
// - **Tables & Task Lists**: GFM extensions are missing.
//
// Next steps:
// 1. Implement recursive block parsing to support nested lists and blockquotes.
// 2. Add support for image tags and link references.

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_heading_and_paragraph() {
        let input = "# Hello World\n\nThis is a paragraph.";
        let parser = Parser::new(input);
        let mut html = String::new();
        push_html(&mut html, parser);

        assert_eq!(
            html,
            "<p># Hello World</p>\n<p>This is a paragraph.</p>\n"
        );
    }

    #[test]
    fn test_inline_formatting() {
        let input = "This has **strong** and *emphasis* and `code`.";
        let parser = Parser::new(input);
        let mut html = String::new();
        push_html(&mut html, parser);

        assert_eq!(
            html,
            "<p>This has <strong>strong</strong> and <em>emphasis</em> and <code>code</code>.</p>\n"
        );
    }

    #[test]
    fn test_links() {
        let input = "Check out [Rust](https://rust-lang.org).";
        let parser = Parser::new(input);
        let mut html = String::new();
        push_html(&mut html, parser);

        assert_eq!(
            html,
            "<p>Check out <a href=\"https://rust-lang.org\">Rust</a>.</p>\n"
        );
    }

    #[test]
    fn test_fenced_code_block() {
        let input = "```rust\nfn main() {}\n```";
        let parser = Parser::new(input);
        let mut html = String::new();
        push_html(&mut html, parser);

        assert_eq!(
            html,
            "<pre><code class=\"language-rust\">fn main() {}\n</code></pre>\n"
        );
    }

    #[test]
    fn test_html_escaping() {
        let input = "Use < & > symbols";
        let parser = Parser::new(input);
        let mut html = String::new();
        push_html(&mut html, parser);

        assert_eq!(
            html,
            "<p>Use &lt; &amp; &gt; symbols</p>\n"
        );
    }
}