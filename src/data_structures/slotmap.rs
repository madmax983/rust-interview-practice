// Comparison to `slotmap`:
// The actual `slotmap` crate has much more advanced features:
// - Specialized key types (macros to generate newtype wrappers around keys so you don't mix up keys
//   from different maps).
// - Secondary maps (maps that use keys from a primary map, but don't manage the generations themselves).
// - DenseSlotMap implementation (keeps values densely packed for iteration performance while keeping
//   sparse generational indices).
//
// What's missing:
// - Iterators (`iter()`, `iter_mut()`, `drain()`).
// - Protection against generation wrapping (e.g., stopping slot reuse if generation hits u32::MAX).
// - Newtype key generation.
//
// Next steps:
// - Implement a `DenseSlotMap` variant that stores values in a packed `Vec` and uses the `slots`
//   array purely as an indirection table, allowing cache-friendly iteration over all values.