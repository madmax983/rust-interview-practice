#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_insert_and_get() {
        let mut sm = SlotMap::new();
        let k1 = sm.insert("hello");
        let k2 = sm.insert("world");

        assert_eq!(sm.len(), 2);
        assert_eq!(sm.get(k1), Some(&"hello"));
        assert_eq!(sm.get(k2), Some(&"world"));
    }

    #[test]
    fn test_remove() {
        let mut sm = SlotMap::new();
        let k1 = sm.insert(10);

        assert_eq!(sm.remove(k1), Some(10));
        assert_eq!(sm.len(), 0);
        assert_eq!(sm.get(k1), None);

        // Double remove should fail
        assert_eq!(sm.remove(k1), None);
    }

    #[test]
    fn test_aba_prevention() {
        let mut sm = SlotMap::new();
        let k1 = sm.insert(100);
        sm.remove(k1);

        // This insert should reuse the slot of k1, but with a new generation
        let k2 = sm.insert(200);

        // The indices should be the same
        assert_eq!(k1.index, k2.index);
        // But the generations must be different
        assert_ne!(k1.generation, k2.generation);

        // Using the old key should fail
        assert_eq!(sm.get(k1), None);
        // Using the new key should succeed
        assert_eq!(sm.get(k2), Some(&200));
    }

    #[test]
    fn test_freelist_chaining() {
        let mut sm = SlotMap::new();
        let k1 = sm.insert(1);
        let k2 = sm.insert(2);
        let k3 = sm.insert(3);

        sm.remove(k2);
        sm.remove(k1);

        // free list should be k1 -> k2
        let k4 = sm.insert(4); // should take k1's old slot
        let k5 = sm.insert(5); // should take k2's old slot

        assert_eq!(k4.index, k1.index);
        assert_eq!(k5.index, k2.index);
    }

    #[test]
    fn test_retain() {
        let mut sm = SlotMap::new();
        let k1 = sm.insert(1);
        let k2 = sm.insert(2);
        let k3 = sm.insert(3);

        sm.retain(|_, val| *val % 2 != 0); // Keep odd numbers

        assert_eq!(sm.len(), 2);
        assert_eq!(sm.get(k1), Some(&1));
        assert_eq!(sm.get(k2), None);
        assert_eq!(sm.get(k3), Some(&3));
    }
}

